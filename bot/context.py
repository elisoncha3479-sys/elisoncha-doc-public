def _build_patient_brief() -> str:
    bits: list[str] = []
    if patient_identity.full_name():
        bits.append(patient_identity.full_name())
    if patient_identity.dob():
        bits.append(f"д.р. {patient_identity.dob()}")
    if patient_identity.city():
        bits.append(patient_identity.city())
    who = ", ".join(bits) if bits else (
        "персональные данные берутся из настроек/анкеты онбординга"
    )
    return (
        f"{patient_identity.patient_noun().capitalize()}: {who}. "
        "Полный медицинский контекст — в профилях специалистов и сводной "
        "истории, которые ты получаешь отдельным блоком. Не выдумывай "
        "данных, которых там нет."
    )


