def load_recent_history(days: int) -> str:
    """Диалоги и текстовые записи из history/ за последние N дней."""
    if not HISTORY_DIR.exists():
        return "(history/ пуст или отсутствует)"
    cutoff = datetime.now() - timedelta(days=days)
    parts = []
    for f in sorted(HISTORY_DIR.glob("*.txt")):
        try:
            mtime = datetime.fromtimestamp(f.stat().st_mtime)
            if mtime >= cutoff:
                snippet = f.read_text(encoding="utf-8")[:2000]
                parts.append(f"### {f.name} ({mtime.strftime('%Y-%m-%d %H:%M')})\n{snippet}\n")
        except Exception as e:
            log.warning("Не прочла %s: %s", f, e)
    return "\n".join(parts) if parts else "(за период не было записей)"


def load_recent_reports(days: int) -> str:
    """Текстовые отчёты из reports/ за последние N дней."""
    if not REPORTS_DIR.exists():
        return ""
    cutoff = datetime.now() - timedelta(days=days)
    parts = []
    for f in sorted(REPORTS_DIR.glob("*")):
        if not f.is_file():
            continue
        try:
            mtime = datetime.fromtimestamp(f.stat().st_mtime)
            if mtime >= cutoff and f.suffix in {".txt", ".md"}:
                snippet = f.read_text(encoding="utf-8")[:1500]
                parts.append(f"### {f.name}\n{snippet}\n")
        except Exception as e:
            log.warning("Не прочла %s: %s", f, e)
    return "\n".join(parts)


def build_report_text_summary(analysis: dict) -> str:
    """Человекочитаемая .md-сводка отчёта для reports/ (аудит 2026-05-16,
    Тема 4, C1). Пишется рядом с PDF, чтобы месячный дайджест
    (load_recent_reports читает .md/.txt) перестал быть пустым."""
    a = analysis or {}
    lines: list[str] = []
    title = (a.get("title") or "Отчёт").strip()
    lines.append(f"# {title}")
    opening = (a.get("opening") or "").strip()
    if opening:
        lines.append(opening)
    headline = a.get("headline") or {}
    h = (headline.get("headline") if isinstance(headline, dict) else "") or ""
    if h.strip():
        lines.append(f"**Главное:** {h.strip()}")
    plan = a.get("action_plan") or []
    if isinstance(plan, list) and plan:
        lines.append("**Что делать:**")
        for item in plan:
            if not isinstance(item, dict):
                continue
            act = (item.get("action") or "").strip()
            if not act:
                continue
            dl = (item.get("deadline") or "").strip()
            lines.append(f"- {act}" + (f" ({dl})" if dl else ""))
    closing = (a.get("personal_closing") or "").strip()
    if closing:
        lines.append(closing)
    text = "\n\n".join(lines).strip()
    return text or "# Отчёт\n\n(пустой разбор)"


